"""Strict, evidence-producing VLM extraction for uploaded travel images."""
# ------- 附件处理的“视觉理解引擎”模块 -------
from __future__ import annotations

import asyncio
import base64
import inspect
import io
from typing import Any, Protocol

from PIL import Image, UnidentifiedImageError
from pydantic import Field

from src.domain import (
    Attachment,
    AttachmentKind,
    AttachmentStatus,
    BoundingBox,
    DocumentType,
    Evidence,
    EvidenceLocator,
    EvidenceSource,
    ExtractedDocument,
    ExtractedField,
    ExtractionStatus,
)
from src.domain.base import DomainModel


class VLMFieldExtraction(DomainModel):
    """One field returned by the model before trusted evidence IDs are assigned."""

    path: str = Field(min_length=1, max_length=255)
    value: str | int | float | bool | None
    confidence: float = Field(ge=0, le=1)
    evidence_text: str = Field(min_length=1, max_length=8000)
    bounding_box: BoundingBox | None
    requires_confirmation: bool


class VLMImageExtraction(DomainModel):
    """Provider-independent strict structured output expected from the VLM."""

    document_type: DocumentType
    raw_text: str = Field(max_length=50000)
    raw_text_confidence: float = Field(ge=0, le=1)
    fields: list[VLMFieldExtraction] = Field(max_length=100)
    warnings: list[str] = Field(max_length=20)


class AttachmentContentService(Protocol):
    def read(
        self, *, user_id: str, attachment_id: Any
    ) -> tuple[Attachment, bytes]: ...

    def update_status(
        self,
        *,
        user_id: str,
        attachment_id: Any,
        status: AttachmentStatus,
        reason: str | None = None,
    ) -> Attachment: ...


class ExtractionRepository(Protocol):
    def save_extraction(
        self,
        user_id: str,
        document: ExtractedDocument,
        evidence: list[Evidence],
    ) -> Any: ...

    def get_latest_extraction(
        self, user_id: str, attachment_id: Any
    ) -> Any | None: ...


class UnsupportedImageFormatError(ValueError):
    """Raised when an attachment is not a supported, correctly labelled image."""


class ImageVLMProcessingError(RuntimeError):
    """Raised when strict image extraction fails."""


class ImageVLMProcessor:
    """Load owned images, call a strict-output VLM, and build auditable evidence."""

    SUPPORTED_MEDIA_TYPES = {
        "image/jpeg": "JPEG",
        "image/jpg": "JPEG",
        "image/png": "PNG",
        "image/webp": "WEBP",
    }
    from src.prompts.prompt_manager import prompt_manager
    PROMPT = prompt_manager.get("vlm_prompt")

    # Some OpenAI-compatible gateways reject the schema generated by LangChain from
    # a Pydantic class. Keep this wire schema explicit and validate the response again
    # with VLMImageExtraction after parsing.
    STRUCTURED_SCHEMA = {
        "title": "VLMImageExtraction",
        "description": "Strict extraction result for one travel image.",
        "type": "object",
        "additionalProperties": False,
        "properties": {
            "document_type": {
                "type": "string",
                "enum": [item.value for item in DocumentType],
            },
            "raw_text": {"type": "string"},
            "raw_text_confidence": {"type": "number"},
            "fields": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "properties": {
                        "path": {"type": "string"},
                        "value": {
                            "anyOf": [
                                {"type": "string"},
                                {"type": "number"},
                                {"type": "boolean"},
                                {"type": "null"},
                            ]
                        },
                        "confidence": {"type": "number"},
                        "evidence_text": {"type": "string"},
                        "bounding_box": {
                            "anyOf": [
                                {
                                    "type": "object",
                                    "additionalProperties": False,
                                    "properties": {
                                        "x": {"type": "number"},
                                        "y": {"type": "number"},
                                        "width": {"type": "number"},
                                        "height": {"type": "number"},
                                    },
                                    "required": ["x", "y", "width", "height"],
                                },
                                {"type": "null"},
                            ]
                        },
                        "requires_confirmation": {"type": "boolean"},
                    },
                    "required": [
                        "path",
                        "value",
                        "confidence",
                        "evidence_text",
                        "bounding_box",
                        "requires_confirmation",
                    ],
                },
            },
            "warnings": {"type": "array", "items": {"type": "string"}},
        },
        "required": [
            "document_type",
            "raw_text",
            "raw_text_confidence",
            "fields",
            "warnings",
        ],
    }

    def __init__(
        self,
        *,
        model: Any,
        attachment_service: AttachmentContentService,
        extraction_repository: ExtractionRepository | None = None,
        extractor_name: str = "image-vlm",
        extractor_version: str = "1",
        review_threshold: float = 0.8,
    ) -> None:
        self.model = model
        self.attachment_service = attachment_service
        self.extraction_repository = extraction_repository
        self.extractor_name = extractor_name
        self.extractor_version = extractor_version
        self.review_threshold = review_threshold
        self._structured_model: Any | None = None

    async def __call__(
        self,
        attachments: list[Attachment],
        *,
        user_id: str,
    ) -> tuple[list[ExtractedDocument], list[Evidence]]:
        documents: list[ExtractedDocument] = []
        evidence: list[Evidence] = []
        for reference in attachments:
            cached = None
            if self.extraction_repository is not None:
                cached = await asyncio.to_thread(
                    self.extraction_repository.get_latest_extraction,
                    user_id,
                    reference.attachment_id,
                )
            if cached is not None:
                document, document_evidence = cached.document, cached.evidence
            else:
                document, document_evidence = await self._process_one(
                    user_id=user_id,
                    attachment_id=reference.attachment_id,
                )
            documents.append(document)
            evidence.extend(document_evidence)
        return documents, evidence

    async def process(
        self,
        attachments: list[Attachment],
        *,
        user_id: str,
        force: bool = False,
    ) -> tuple[list[ExtractedDocument], list[Evidence]]:
        """Process attachments, optionally bypassing persisted reviewed results."""
        if not force:
            return await self(attachments, user_id=user_id)
        documents: list[ExtractedDocument] = []
        evidence: list[Evidence] = []
        for reference in attachments:
            document, document_evidence = await self._process_one(
                user_id=user_id,
                attachment_id=reference.attachment_id,
            )
            documents.append(document)
            evidence.extend(document_evidence)
        return documents, evidence

    async def _process_one(
        self, *, user_id: str, attachment_id: Any
    ) -> tuple[ExtractedDocument, list[Evidence]]:
        try:
            # 读取附件内容，验证图片格式，调用 VLM 提取信息，构建结果，并更新状态为 processed
            await asyncio.to_thread(
                self.attachment_service.update_status,
                user_id=user_id,
                attachment_id=attachment_id,
                status=AttachmentStatus.PROCESSING,
            )
            attachment, content = await asyncio.to_thread(
                self.attachment_service.read,
                user_id=user_id,
                attachment_id=attachment_id,
            )
            media_type = self._validate_image(attachment, content)
            extraction = await self._extract(content, media_type)
            document, evidence = self._build_result(attachment, extraction)
            if self.extraction_repository is not None:
                await asyncio.to_thread(
                    self.extraction_repository.save_extraction,
                    user_id,
                    document,
                    evidence,
                )
            # 处理完成后更新状态为 processed,并返回结果
            await asyncio.to_thread(
                self.attachment_service.update_status,
                user_id=user_id,
                attachment_id=attachment_id,
                status=AttachmentStatus.PROCESSED,
            )
            return document, evidence
        except Exception as error:
            reason = (str(error).strip() or error.__class__.__name__)[:1000]
            try:
                await asyncio.to_thread(
                    self.attachment_service.update_status,
                    user_id=user_id,
                    attachment_id=attachment_id,
                    status=AttachmentStatus.FAILED,
                    reason=reason,
                )
            except Exception:
                pass
            if isinstance(error, ImageVLMProcessingError):
                raise
            raise ImageVLMProcessingError(
                f"Image extraction failed for attachment {attachment_id}: {reason}"
            ) from error

    def _validate_image(self, attachment: Attachment, content: bytes) -> str:
        if attachment.kind != AttachmentKind.IMAGE:
            raise UnsupportedImageFormatError("Only image attachments are supported.")
        media_type = attachment.media_type.lower()
        expected_format = self.SUPPORTED_MEDIA_TYPES.get(media_type)
        if expected_format is None:
            raise UnsupportedImageFormatError(
                "Only JPEG/JPG, PNG, and WebP images are supported."
            )
        try:
            with Image.open(io.BytesIO(content)) as image:
                actual_format = str(image.format or "").upper()
                image.verify()
        except (UnidentifiedImageError, OSError, SyntaxError) as error:
            raise UnsupportedImageFormatError("Stored content is not a valid image.") from error
        if actual_format != expected_format:
            raise UnsupportedImageFormatError(
                f"Stored image format {actual_format!r} does not match {media_type!r}."
            )
        return media_type

    async def _extract(self, content: bytes, media_type: str) -> VLMImageExtraction:
        if self._structured_model is None:
            self._structured_model = self.model.with_structured_output(
                self.STRUCTURED_SCHEMA,
                method="json_schema",
                strict=True,
            )
        data_url = (
            f"data:{media_type};base64,"
            + base64.b64encode(content).decode("ascii")
        )
        messages = [
            {
                "role": "user",
                "content": [
                    {"type": "text", "text": self.PROMPT},
                    {"type": "image_url", "image_url": {"url": data_url}},
                ],
            }
        ]
        if hasattr(self._structured_model, "ainvoke"):
            raw_result = self._structured_model.ainvoke(messages)
            raw_result = await raw_result if inspect.isawaitable(raw_result) else raw_result
        else:
            raw_result = await asyncio.to_thread(self._structured_model.invoke, messages)
        return VLMImageExtraction.model_validate(raw_result)

    def _build_result(
        self, attachment: Attachment, extraction: VLMImageExtraction
    ) -> tuple[ExtractedDocument, list[Evidence]]:
        evidence: list[Evidence] = []
        evidence_ids = []
        raw_text = extraction.raw_text.strip()
        for index in range(0, len(raw_text), 8000):
            raw_evidence = Evidence(
                source=EvidenceSource.ATTACHMENT,
                source_id=str(attachment.attachment_id),
                content=raw_text[index : index + 8000],
                confidence=extraction.raw_text_confidence,
                metadata={
                    "kind": "vlm_transcription",
                    "chunk_index": index // 8000,
                },
            )
            evidence.append(raw_evidence)
            evidence_ids.append(raw_evidence.evidence_id)

        fields: list[ExtractedField] = []
        needs_review = not extraction.fields
        for item in extraction.fields:
            field_evidence = Evidence(
                source=EvidenceSource.ATTACHMENT,
                source_id=str(attachment.attachment_id),
                content=item.evidence_text,
                confidence=item.confidence,
                locator=EvidenceLocator(bounding_box=item.bounding_box)
                if item.bounding_box
                else None,
                metadata={"field_path": item.path, "kind": "vlm_field"},
            )
            evidence.append(field_evidence)
            evidence_ids.append(field_evidence.evidence_id)
            requires_confirmation = (
                item.requires_confirmation or item.confidence < self.review_threshold
            )
            needs_review = needs_review or requires_confirmation
            fields.append(
                ExtractedField(
                    path=item.path,
                    value=item.value,
                    confidence=item.confidence,
                    evidence_ids=[field_evidence.evidence_id],
                    requires_confirmation=requires_confirmation,
                )
            )

        warnings = list(extraction.warnings)
        if not extraction.fields:
            warnings.append("No verifiable structured fields were extracted.")
        document = ExtractedDocument(
            attachment_id=attachment.attachment_id,
            document_type=extraction.document_type,
            status=(
                ExtractionStatus.NEEDS_REVIEW
                if needs_review
                else ExtractionStatus.COMPLETED
            ),
            fields=fields,
            evidence_ids=evidence_ids,
            raw_text=extraction.raw_text,
            extractor=self.extractor_name,
            extractor_version=self.extractor_version,
            warnings=warnings,
        )
        return document, evidence
